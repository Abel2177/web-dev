import { notFound } from "next/navigation";
import { dishes, findDish } from "../dishes";
import AddToCart from "../AddToCart";

// Tell Next.js which IDs to pre-render at build time.
export function generateStaticParams() {
  return dishes.map((dish) => ({ id: String(dish.id) }));
}

// ─── Dynamic metadata ─────────────────────────────────────────────────────────
export async function generateMetadata({ params }) {
  const { id } = await params;
  const dish = findDish(id);

  if (!dish) return { title: "Dish not found" };

  const totalTime = dish.prepTimeMinutes + dish.cookTimeMinutes;
  const description = `${dish.name} — ${dish.cuisine} · ${dish.difficulty}. Ready in ${totalTime} minutes. Rated ★ ${dish.rating} by ${dish.reviewCount} reviewers.`;

  return {
    // Root template → "{dish.name} · Addis Eats"
    title: dish.name,
    description,
    alternates: {
      canonical: `/menu/${dish.id}`,
    },
    openGraph: {
      title: `${dish.name} · Addis Eats`,
      description,
      url: `/menu/${dish.id}`,
      images: [
        {
          // /og/{id}.jpg generated by opengraph-image.jsx; falls back to the
          // dish's own hosted image so social previews always have something.
          url: dish.image,
          width: 1200,
          height: 630,
          alt: dish.name,
        },
      ],
      type: "website",
      locale: "en_ET",
    },
    twitter: {
      card: "summary_large_image",
      title: `${dish.name} · Addis Eats`,
      description,
      images: [dish.image],
    },
  };
}

// ─── JSON-LD structured data (MenuItem schema) ────────────────────────────────
function DishJsonLd({ dish }) {
  const totalTime = dish.prepTimeMinutes + dish.cookTimeMinutes;
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Recipe",
    name: dish.name,
    description: `${dish.cuisine} ${dish.name}. ${dish.difficulty} difficulty.`,
    image: [dish.image],
    recipeCategory: dish.cuisine,
    recipeCuisine: dish.cuisine,
    prepTime: `PT${dish.prepTimeMinutes}M`,
    cookTime: `PT${dish.cookTimeMinutes}M`,
    totalTime: `PT${totalTime}M`,
    recipeYield: `${dish.servings} servings`,
    aggregateRating: {
      "@type": "AggregateRating",
      ratingValue: dish.rating,
      reviewCount: dish.reviewCount,
    },
    recipeIngredient: dish.ingredients,
    recipeInstructions: dish.instructions
      ? dish.instructions.map((step) => ({
          "@type": "HowToStep",
          text: step,
        }))
      : [],
    keywords: dish.tags?.join(", ") ?? dish.cuisine,
  };

  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
    />
  );
}

// ─── Page component ───────────────────────────────────────────────────────────
export default async function DishPage({ params }) {
  const { id } = await params;
  const dish = findDish(id);
  if (!dish) notFound();

  return (
    <>
      {/* Inject JSON-LD into <head> via Next.js script hoisting */}
      <DishJsonLd dish={dish} />

      <article className="dish-detail">
        <p className="eyebrow">
          {dish.cuisine} · {dish.difficulty}
        </p>
        <h1>{dish.name}</h1>
        <p>{dish.ingredients.join(", ")}</p>
        <p className="price">
          {dish.prepTimeMinutes + dish.cookTimeMinutes} minutes · Serves{" "}
          {dish.servings} · ★ {dish.rating}
        </p>
        <AddToCart dish={dish} />
      </article>
    </>
  );
}